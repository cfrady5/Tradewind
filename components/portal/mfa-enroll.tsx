"use client";

import { useState, useTransition } from "react";
import { startEnrollment, verifyMfa } from "@/lib/portal/actions";
import { Btn, inputClass } from "./primitives";

/** Authenticator-app enrollment: the QR code and secret never leave the server response for this user. */
export function MfaEnroll() {
  const [data, setData] = useState<{ factorId: string; qr: string; secret: string } | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [pending, start] = useTransition();

  if (!data) {
    return (
      <div>
        <p className="text-sm text-ink-muted">Every employee account uses an authenticator app (Microsoft Authenticator, Google Authenticator, 1Password or similar) as a second factor.</p>
        {error && <p role="alert" className="mt-3 text-sm text-[#8a1c1c]">{error}</p>}
        <Btn type="button" className="mt-5 w-full" disabled={pending} onClick={() => start(async () => { const r = await startEnrollment(); if ("error" in r) setError(r.error); else setData(r); })}>
          {pending ? "Preparing…" : "Set up authenticator app"}
        </Btn>
      </div>
    );
  }
  return (
    <form action={verifyMfa} className="space-y-4">
      <input type="hidden" name="factorId" value={data.factorId} />
      <input type="hidden" name="enrolling" value="1" />
      <ol className="list-decimal space-y-1 pl-5 text-sm text-ink-muted">
        <li>Open your authenticator app and scan this code.</li>
        <li>Enter the 6-digit code it shows.</li>
      </ol>
      {/* The QR image is an SVG data URI generated by Supabase Auth for this factor. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={data.qr} alt="QR code for your authenticator app" width={200} height={200} className="mx-auto rounded-md border border-line" />
      <details className="text-xs text-ink-muted">
        <summary className="cursor-pointer font-semibold">Can&rsquo;t scan? Enter the key manually</summary>
        <code className="mt-2 block break-all rounded-sm bg-cloud p-2 font-mono text-[0.75rem] text-navy">{data.secret}</code>
      </details>
      <div>
        <label htmlFor="code" className="block text-xs font-semibold uppercase tracking-[0.08em] text-ink-muted">Verification code</label>
        <input id="code" name="code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9 ]{6,7}" required autoFocus className={`${inputClass} mt-1 text-center font-mono text-lg tracking-[0.3em]`} />
      </div>
      <Btn type="submit" className="w-full">Verify and continue</Btn>
    </form>
  );
}
